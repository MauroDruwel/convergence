import { RepoBrain } from '../durable-objects/RepoBrain.js';

export async function runSwarmSimulation(iterations: number = 10, brain?: RepoBrain) {
  const repo = brain || new RepoBrain();
  console.log(`🤖 Launching Convergence Swarm Simulation with ${iterations} waves...`);

  const agentNames = [
    'agent_sentinel',
    'agent_payment',
    'agent_auth',
    'agent_optimizer',
    'agent_fuzzer',
    'agent_refactor',
    'agent_docs',
    'agent_tester',
  ];

  for (let wave = 1; wave <= iterations; wave++) {
    console.log(`\n🌊 [Wave ${wave}/${iterations}] Concurrent Agent Dispatch`);
    const tasks = agentNames.map(async (name, idx) => {
      const funcName = `module_${name}_${wave}`;
      const codeSnippet = `\n// Generated by ${name}\nexport function ${funcName}(): string {\n  return "Execution from ${name} at wave ${wave}";\n}\n`;

      const current = repo.getState().files['index.ts'] || '';
      const updated = current + codeSnippet;

      const result = await repo.handleAgentCommit({
        agentId: name,
        filename: 'index.ts',
        sourceCode: updated,
        message: `Agent ${name} adds ${funcName}`,
      });

      console.log(
        `  ⚡ ${name}: ${result.cleanMerge ? 'CLEAN MERGE (AST-CRDT)' : 'ARBITRATED'} [Commit: ${result.commitId}]`
      );
    });

    await Promise.all(tasks);

    // Occasionally trigger a Reverse PR
    if (wave % 3 === 0) {
      const pr = repo.createReversePR(
        'agent_payment',
        'Should payment retry backoff be exponential (2s, 4s, 8s) or linear (3s, 3s, 3s)?',
        ['Exponential Backoff', 'Linear Backoff', 'Immediate Fail']
      );
      console.log(`  ❓ [Reverse PR Raised] ${pr.question}`);
      // Auto-resolve after a second
      repo.resolveReversePR(pr.id, 'Exponential Backoff');
      console.log(`  ✅ [Human Steering Decision] Selected: "Exponential Backoff"`);
    }
  }

  const finalState = repo.getState();
  console.log(`\n🎉 Swarm Simulation Complete!`);
  console.log(`  - Total Symbols in index.ts: ${finalState.symbols['index.ts']?.length || 0}`);
  console.log(`  - Total Events Logged: ${finalState.events.length}`);
  console.log(`  - Lamport Clock: ${finalState.lamportClock}`);

  return finalState;
}

if (process.argv[1]?.endsWith('swarm-simulator.ts')) {
  runSwarmSimulation(4).catch(console.error);
}
